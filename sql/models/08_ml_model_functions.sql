CREATE OR REPLACE FUNCTION AGENT_GET_FLEET_HEALTH()
RETURNS OBJECT
AS
$$
SELECT OBJECT_CONSTRUCT(
    'vehicles', (SELECT COUNT(*) FROM ROCKET_LAB_INTELLIGENCE.RAW.VEHICLES),
    'flown', (SELECT COUNT(*) FROM ROCKET_LAB_INTELLIGENCE.RAW.VEHICLES WHERE STATUS = 'Flown'),
    'in_production', (SELECT COUNT(*) FROM ROCKET_LAB_INTELLIGENCE.RAW.VEHICLES WHERE STATUS = 'In Production'),
    'ready_for_launch', (SELECT COUNT(*) FROM ROCKET_LAB_INTELLIGENCE.RAW.VEHICLES WHERE STATUS = 'Ready for Launch'),
    'active_test_articles', (SELECT COUNT(*) FROM ROCKET_LAB_INTELLIGENCE.RAW.VEHICLES WHERE STATUS = 'Active Test'),
    'lost', (SELECT COUNT(*) FROM ROCKET_LAB_INTELLIGENCE.RAW.VEHICLES WHERE STATUS = 'Lost'),
    'electron', (SELECT COUNT(*) FROM ROCKET_LAB_INTELLIGENCE.RAW.VEHICLES WHERE VEHICLE_TYPE = 'Electron'),
    'haste', (SELECT COUNT(*) FROM ROCKET_LAB_INTELLIGENCE.RAW.VEHICLES WHERE VEHICLE_TYPE = 'HASTE'),
    'neutron', (SELECT COUNT(*) FROM ROCKET_LAB_INTELLIGENCE.RAW.VEHICLES WHERE VEHICLE_TYPE = 'Neutron'),
    'components', (SELECT COUNT(*) FROM ROCKET_LAB_INTELLIGENCE.RAW.COMPONENTS),
    'failed_components', (SELECT COUNT(*) FROM ROCKET_LAB_INTELLIGENCE.RAW.COMPONENTS WHERE STATUS = 'Failed'),
    'needs_replacement', (SELECT COUNT(*) FROM ROCKET_LAB_INTELLIGENCE.RAW.COMPONENTS WHERE STATUS = 'Needs Replacement'),
    'degraded_components', (SELECT COUNT(*) FROM ROCKET_LAB_INTELLIGENCE.RAW.COMPONENTS WHERE STATUS = 'Degraded'),
    'missions_flown', (SELECT COUNT(*) FROM ROCKET_LAB_INTELLIGENCE.RAW.MISSIONS WHERE ACTUAL_LAUNCH_DATE IS NOT NULL),
    'successful_missions', (SELECT COUNT(*) FROM ROCKET_LAB_INTELLIGENCE.RAW.MISSIONS WHERE STATUS = 'Success'),
    'failed_missions', (SELECT COUNT(*) FROM ROCKET_LAB_INTELLIGENCE.RAW.MISSIONS WHERE STATUS = 'Failure'),
    'missions_scheduled', (SELECT COUNT(*) FROM ROCKET_LAB_INTELLIGENCE.RAW.MISSIONS WHERE ACTUAL_LAUNCH_DATE IS NULL),
    'open_anomalies', (SELECT COUNT(*) FROM ROCKET_LAB_INTELLIGENCE.RAW.ANOMALIES WHERE RESOLVED_AT IS NULL),
    'customers', (SELECT COUNT(*) FROM ROCKET_LAB_INTELLIGENCE.RAW.CUSTOMERS))
$$;

CREATE OR REPLACE FUNCTION AGENT_GET_MISSION_SUMMARY()
RETURNS OBJECT
AS
$$
SELECT OBJECT_CONSTRUCT(
    'missions', (SELECT COUNT(*) FROM ROCKET_LAB_INTELLIGENCE.RAW.MISSIONS),
    'success_rate_pct', (SELECT ROUND(100 * DIV0(COUNT_IF(STATUS = 'Success'), COUNT_IF(ACTUAL_LAUNCH_DATE IS NOT NULL)), 1)
                         FROM ROCKET_LAB_INTELLIGENCE.RAW.MISSIONS),
    'avg_delay_days', (SELECT ROUND(AVG(DELAY_DAYS), 1) FROM ROCKET_LAB_INTELLIGENCE.RAW.MISSIONS WHERE DELAY_DAYS IS NOT NULL),
    'backlog_usd', (SELECT ROUND(SUM(CONTRACT_VALUE_USD), 0) FROM ROCKET_LAB_INTELLIGENCE.RAW.MISSIONS WHERE ACTUAL_LAUNCH_DATE IS NULL),
    'boosters_recovered', (SELECT COUNT(*) FROM ROCKET_LAB_INTELLIGENCE.RAW.MISSIONS WHERE BOOSTER_RECOVERED),
    'next_launches', (SELECT ARRAY_AGG(OBJECT_CONSTRUCT(
        'mission', MISSION_NAME, 'vehicle', VEHICLE_TYPE, 'planned', PLANNED_LAUNCH_DATE::VARCHAR))
        FROM (SELECT MISSION_NAME, VEHICLE_TYPE, PLANNED_LAUNCH_DATE
              FROM ROCKET_LAB_INTELLIGENCE.RAW.MISSIONS
              WHERE ACTUAL_LAUNCH_DATE IS NULL ORDER BY PLANNED_LAUNCH_DATE LIMIT 5)))
$$;

CREATE OR REPLACE FUNCTION AGENT_GET_COMPONENTS_AT_RISK()
RETURNS ARRAY
AS
$$
SELECT ARRAY_AGG(OBJECT_CONSTRUCT(
    'component', COMPONENT_NAME, 'type', COMPONENT_TYPE, 'status', COMPONENT_STATUS,
    'vehicle', VEHICLE_NAME, 'life_used_pct', LIFE_USED_PCT,
    'rul_cycles', INSPECTION_RUL_CYCLES, 'supplier', SUPPLIER_NAME,
    'supplier_quality', QUALITY_RATING, 'test_failures', TEST_FAIL_COUNT))
FROM (SELECT * FROM ROCKET_LAB_INTELLIGENCE.ANALYTICS.COMPONENT_HEALTH
      WHERE COMPONENT_STATUS IN ('Failed', 'Needs Replacement', 'Degraded')
      ORDER BY LIFE_USED_PCT DESC LIMIT 25)
$$;

CREATE OR REPLACE FUNCTION AGENT_GET_MAINTENANCE_COST_SUMMARY()
RETURNS OBJECT
AS
$$
SELECT OBJECT_CONSTRUCT(
    'events_12m', COUNT(*),
    'cost_usd_12m', ROUND(SUM(COST_USD), 0),
    'avg_hours', ROUND(AVG(DURATION_HOURS), 1),
    'scrapped', COUNT_IF(OUTCOME = 'Scrapped'),
    'by_type', (SELECT ARRAY_AGG(OBJECT_CONSTRUCT('type', MAINTENANCE_TYPE, 'events', N, 'cost_usd', COST))
                FROM (SELECT MAINTENANCE_TYPE, COUNT(*) AS N, ROUND(SUM(COST_USD), 0) AS COST
                      FROM ROCKET_LAB_INTELLIGENCE.RAW.MAINTENANCE_RECORDS
                      WHERE PERFORMED_AT >= DATEADD(MONTH, -12, CURRENT_TIMESTAMP())
                      GROUP BY 1 ORDER BY 3 DESC)))
FROM ROCKET_LAB_INTELLIGENCE.RAW.MAINTENANCE_RECORDS
WHERE PERFORMED_AT >= DATEADD(MONTH, -12, CURRENT_TIMESTAMP())
$$;

CREATE OR REPLACE FUNCTION AGENT_GET_ANOMALY_REPORT()
RETURNS OBJECT
AS
$$
SELECT OBJECT_CONSTRUCT(
    'open', COUNT_IF(RESOLVED_AT IS NULL),
    'critical_open', COUNT_IF(RESOLVED_AT IS NULL AND SEVERITY = 'Critical'),
    'schedule_impact_days', SUM(SCHEDULE_IMPACT_DAYS),
    'avg_resolution_hours', ROUND(AVG(IFF(RESOLVED_AT IS NULL, NULL, DATEDIFF(HOUR, REPORTED_AT, RESOLVED_AT))), 1),
    'top_root_causes', (SELECT ARRAY_AGG(OBJECT_CONSTRUCT('cause', ROOT_CAUSE, 'count', N))
                        FROM (SELECT ROOT_CAUSE, COUNT(*) AS N FROM ROCKET_LAB_INTELLIGENCE.RAW.ANOMALIES
                              GROUP BY 1 ORDER BY 2 DESC LIMIT 5)))
FROM ROCKET_LAB_INTELLIGENCE.RAW.ANOMALIES
$$;

CREATE OR REPLACE FUNCTION AGENT_GET_RUL_ESTIMATES()
RETURNS ARRAY
AS
$$
SELECT ARRAY_AGG(OBJECT_CONSTRUCT(
    'component', COMPONENT_NAME, 'type', COMPONENT_TYPE, 'vehicle', VEHICLE_NAME,
    'rul_cycles', INSPECTION_RUL_CYCLES, 'life_used_pct', LIFE_USED_PCT,
    'status', COMPONENT_STATUS))
FROM (SELECT * FROM ROCKET_LAB_INTELLIGENCE.ANALYTICS.COMPONENT_HEALTH
      WHERE COMPONENT_STATUS NOT IN ('Flown', 'Failed')
      ORDER BY INSPECTION_RUL_CYCLES LIMIT 25)
$$;

CREATE OR REPLACE FUNCTION AGENT_GET_CUSTOMER_360(CUSTOMER_NAME_FILTER VARCHAR)
RETURNS OBJECT
AS
$$
SELECT OBJECT_CONSTRUCT(
    'customer', c.CUSTOMER_NAME, 'type', c.CUSTOMER_TYPE, 'segment', c.SEGMENT,
    'lifecycle', c.LIFECYCLE_STAGE, 'support_tier', c.SUPPORT_TIER,
    'account_manager', c.ACCOUNT_MANAGER, 'csm', c.CSM_NAME,
    'arr_usd', c.ACTIVE_ARR_USD, 'days_to_renewal', c.DAYS_TO_RENEWAL,
    'missions', c.MISSION_COUNT, 'failed_missions', c.FAILED_MISSIONS,
    'launch_backlog_usd', c.LAUNCH_BACKLOG_USD, 'spacecraft', c.SPACECRAFT_COUNT,
    'nps', c.LATEST_NPS, 'open_tickets', c.OPEN_TICKETS,
    'critical_tickets', c.CRITICAL_OPEN_TICKETS, 'late_payment_pct', c.LATE_PAYMENT_PCT,
    'overdue_usd', c.OVERDUE_USD, 'critical_anomalies', c.CRITICAL_ANOMALIES,
    'churn_risk', s.CHURN_RISK, 'churn_tier', s.CHURN_RISK_TIER,
    'health_score', s.HEALTH_SCORE, 'expansion_score', s.EXPANSION_SCORE,
    'risk_drivers', s.TOP_DRIVERS)
FROM ROCKET_LAB_INTELLIGENCE.ANALYTICS.CUSTOMER_360 c
LEFT JOIN ROCKET_LAB_INTELLIGENCE.ANALYTICS.CUSTOMER_ML_SCORES s ON s.CUSTOMER_ID = c.CUSTOMER_ID
WHERE c.CUSTOMER_NAME ILIKE '%' || CUSTOMER_NAME_FILTER || '%'
ORDER BY c.ACTIVE_ARR_USD DESC LIMIT 1
$$;

CREATE OR REPLACE FUNCTION AGENT_GET_CHURN_RISK_LIST()
RETURNS ARRAY
AS
$$
SELECT ARRAY_AGG(OBJECT_CONSTRUCT(
    'customer', c.CUSTOMER_NAME, 'segment', c.SEGMENT, 'lifecycle', c.LIFECYCLE_STAGE,
    'churn_risk', s.CHURN_RISK, 'tier', s.CHURN_RISK_TIER, 'health_score', s.HEALTH_SCORE,
    'arr_usd', c.ACTIVE_ARR_USD, 'days_to_renewal', c.DAYS_TO_RENEWAL,
    'drivers', s.TOP_DRIVERS))
FROM (SELECT * FROM ROCKET_LAB_INTELLIGENCE.ANALYTICS.CUSTOMER_ML_SCORES
      ORDER BY CHURN_RISK DESC LIMIT 15) s
JOIN ROCKET_LAB_INTELLIGENCE.ANALYTICS.CUSTOMER_360 c ON c.CUSTOMER_ID = s.CUSTOMER_ID
$$;

CREATE OR REPLACE FUNCTION AGENT_GET_EXPANSION_OPPORTUNITIES()
RETURNS ARRAY
AS
$$
SELECT ARRAY_AGG(OBJECT_CONSTRUCT(
    'customer', c.CUSTOMER_NAME, 'segment', c.SEGMENT, 'expansion_score', s.EXPANSION_SCORE,
    'arr_usd', c.ACTIVE_ARR_USD, 'nps', c.LATEST_NPS,
    'automation_pct', c.AVG_AUTOMATION_PCT_90D))
FROM (SELECT * FROM ROCKET_LAB_INTELLIGENCE.ANALYTICS.CUSTOMER_ML_SCORES
      ORDER BY EXPANSION_SCORE DESC LIMIT 15) s
JOIN ROCKET_LAB_INTELLIGENCE.ANALYTICS.CUSTOMER_360 c ON c.CUSTOMER_ID = s.CUSTOMER_ID
WHERE c.LIFECYCLE_STAGE <> 'Churned'
$$;

CREATE OR REPLACE FUNCTION AGENT_GET_RENEWAL_CALENDAR(DAYS_AHEAD NUMBER)
RETURNS ARRAY
AS
$$
SELECT ARRAY_AGG(OBJECT_CONSTRUCT(
    'customer', c.CUSTOMER_NAME, 'segment', c.SEGMENT, 'renewal_date', c.CONTRACT_END_DATE::VARCHAR,
    'days_to_renewal', c.DAYS_TO_RENEWAL, 'arr_usd', c.ACTIVE_ARR_USD,
    'churn_tier', s.CHURN_RISK_TIER, 'health_score', s.HEALTH_SCORE))
FROM ROCKET_LAB_INTELLIGENCE.ANALYTICS.CUSTOMER_360 c
LEFT JOIN ROCKET_LAB_INTELLIGENCE.ANALYTICS.CUSTOMER_ML_SCORES s ON s.CUSTOMER_ID = c.CUSTOMER_ID
WHERE c.DAYS_TO_RENEWAL BETWEEN 0 AND DAYS_AHEAD
$$;

CREATE OR REPLACE FUNCTION AGENT_GET_ACCOUNT_HEALTH_SUMMARY()
RETURNS OBJECT
AS
$$
SELECT OBJECT_CONSTRUCT(
    'customers', COUNT(*),
    'avg_health_score', ROUND(AVG(s.HEALTH_SCORE), 1),
    'high_churn_risk', COUNT_IF(s.CHURN_RISK_TIER = 'High'),
    'medium_churn_risk', COUNT_IF(s.CHURN_RISK_TIER = 'Medium'),
    'low_churn_risk', COUNT_IF(s.CHURN_RISK_TIER = 'Low'),
    'arr_at_risk_usd', ROUND(SUM(IFF(s.CHURN_RISK_TIER = 'High', c.ACTIVE_ARR_USD, 0)), 0),
    'churned', (SELECT COUNT(*) FROM ROCKET_LAB_INTELLIGENCE.RAW.CUSTOMERS WHERE LIFECYCLE_STAGE = 'Churned'),
    'renewals_due_120d', (SELECT COUNT(*) FROM ROCKET_LAB_INTELLIGENCE.ANALYTICS.CUSTOMER_360
                          WHERE DAYS_TO_RENEWAL BETWEEN 0 AND 120))
FROM ROCKET_LAB_INTELLIGENCE.ANALYTICS.CUSTOMER_360 c
JOIN ROCKET_LAB_INTELLIGENCE.ANALYTICS.CUSTOMER_ML_SCORES s ON s.CUSTOMER_ID = c.CUSTOMER_ID
$$;
