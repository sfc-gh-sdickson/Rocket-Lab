/*=============================================================================
  Rocket Lab Intelligence Agent
  Step 6: Cortex Search Services

  Execution Order: 6 of 9
  Description: Eight Cortex Search services for retrieval over mission
               documents, test failure reports, the knowledge base,
               maintenance records, anomalies, customer interactions,
               support tickets and survey comments.
               Does not create or modify any tables.
=============================================================================*/

USE DATABASE ROCKET_LAB_INTELLIGENCE;
USE SCHEMA ANALYTICS;
USE WAREHOUSE ROCKET_LAB_WH;

CREATE OR REPLACE CORTEX SEARCH SERVICE RL_MISSION_DOCUMENT_SEARCH
  ON CONTENT
  ATTRIBUTES DOC_TYPE, VEHICLE_TYPE, SITE_ID
  WAREHOUSE = ROCKET_LAB_WH
  TARGET_LAG = '1 day'
  COMMENT = 'Mission requirements, flight readiness reviews, post-flight reports and payload interface documents'
AS
  SELECT d.DOC_ID, d.DOC_TITLE, d.DOC_TYPE, d.CONTENT, d.AUTHOR, d.CREATED_AT,
         m.MISSION_NAME, m.VEHICLE_TYPE, m.SITE_ID, c.CUSTOMER_NAME
  FROM ROCKET_LAB_INTELLIGENCE.RAW.MISSION_DOCUMENTS d
  JOIN ROCKET_LAB_INTELLIGENCE.RAW.MISSIONS m ON m.MISSION_ID = d.MISSION_ID
  JOIN ROCKET_LAB_INTELLIGENCE.RAW.CUSTOMERS c ON c.CUSTOMER_ID = m.CUSTOMER_ID;

CREATE OR REPLACE CORTEX SEARCH SERVICE RL_TEST_FAILURE_SEARCH
  ON CONTENT
  ATTRIBUTES COMPONENT_TYPE, SEVERITY, ROOT_CAUSE
  WAREHOUSE = ROCKET_LAB_WH
  TARGET_LAG = '1 day'
  COMMENT = 'Failure analysis reports for tests that did not pass acceptance'
AS
  SELECT r.REPORT_ID, r.REPORT_TITLE, r.CONTENT, r.COMPONENT_TYPE, r.SEVERITY,
         r.ROOT_CAUSE, r.CORRECTIVE_ACTION, s.SUPPLIER_NAME, r.CREATED_AT
  FROM ROCKET_LAB_INTELLIGENCE.RAW.TEST_FAILURE_REPORTS r
  JOIN ROCKET_LAB_INTELLIGENCE.RAW.SUPPLIERS s ON s.SUPPLIER_ID = r.SUPPLIER_ID;

CREATE OR REPLACE CORTEX SEARCH SERVICE RL_KNOWLEDGE_SEARCH
  ON CONTENT
  ATTRIBUTES CATEGORY, VEHICLE_TYPE
  WAREHOUSE = ROCKET_LAB_WH
  TARGET_LAG = '1 day'
  COMMENT = 'Engineering and customer success knowledge base'
AS
  SELECT ARTICLE_ID, TITLE, CATEGORY, VEHICLE_TYPE, CONTENT, TAGS, AUTHOR, UPDATED_AT
  FROM ROCKET_LAB_INTELLIGENCE.RAW.KNOWLEDGE_BASE;

CREATE OR REPLACE CORTEX SEARCH SERVICE RL_MAINTENANCE_SEARCH
  ON SEARCH_TEXT
  ATTRIBUTES MAINTENANCE_TYPE, VEHICLE_TYPE, OUTCOME
  WAREHOUSE = ROCKET_LAB_WH
  TARGET_LAG = '1 day'
  COMMENT = 'Maintenance and refurbishment work records'
AS
  SELECT m.MAINTENANCE_ID, m.MAINTENANCE_TYPE, v.VEHICLE_TYPE, v.VEHICLE_NAME, m.FACILITY,
         m.DESCRIPTION || COALESCE(' | Parts replaced: ' || m.PARTS_REPLACED, '') || ' | Outcome: ' || m.OUTCOME AS SEARCH_TEXT,
         m.OUTCOME, m.COST_USD, m.PERFORMED_AT
  FROM ROCKET_LAB_INTELLIGENCE.RAW.MAINTENANCE_RECORDS m
  JOIN ROCKET_LAB_INTELLIGENCE.RAW.VEHICLES v ON v.VEHICLE_ID = m.VEHICLE_ID;

CREATE OR REPLACE CORTEX SEARCH SERVICE RL_ANOMALY_SEARCH
  ON DESCRIPTION
  ATTRIBUTES ANOMALY_TYPE, SEVERITY, PHASE, ROOT_CAUSE
  WAREHOUSE = ROCKET_LAB_WH
  TARGET_LAG = '1 day'
  COMMENT = 'Anomaly and nonconformance descriptions'
AS
  SELECT a.ANOMALY_ID, a.ANOMALY_TYPE, a.SEVERITY, a.PHASE, a.DESCRIPTION,
         a.ROOT_CAUSE, a.RESOLUTION, v.VEHICLE_TYPE, a.SCHEDULE_IMPACT_DAYS, a.REPORTED_AT
  FROM ROCKET_LAB_INTELLIGENCE.RAW.ANOMALIES a
  JOIN ROCKET_LAB_INTELLIGENCE.RAW.VEHICLES v ON v.VEHICLE_ID = a.VEHICLE_ID;

CREATE OR REPLACE CORTEX SEARCH SERVICE RL_INTERACTION_SEARCH
  ON SUMMARY
  ATTRIBUTES INTERACTION_TYPE, SENTIMENT, SEGMENT
  WAREHOUSE = ROCKET_LAB_WH
  TARGET_LAG = '1 day'
  COMMENT = 'Customer meeting notes and interaction summaries'
AS
  SELECT i.INTERACTION_ID, i.INTERACTION_TYPE, i.SUBJECT, i.SUMMARY, i.SENTIMENT,
         i.NEXT_STEPS, c.CUSTOMER_NAME, c.SEGMENT, i.INTERACTION_DATE
  FROM ROCKET_LAB_INTELLIGENCE.RAW.INTERACTIONS i
  JOIN ROCKET_LAB_INTELLIGENCE.RAW.CUSTOMERS c ON c.CUSTOMER_ID = i.CUSTOMER_ID;

CREATE OR REPLACE CORTEX SEARCH SERVICE RL_SUPPORT_TICKET_SEARCH
  ON DESCRIPTION
  ATTRIBUTES CATEGORY, PRIORITY, STATUS
  WAREHOUSE = ROCKET_LAB_WH
  TARGET_LAG = '1 day'
  COMMENT = 'Customer support and mission management tickets'
AS
  SELECT t.TICKET_ID, t.CATEGORY, t.PRIORITY, t.STATUS, t.SUBJECT, t.DESCRIPTION,
         c.CUSTOMER_NAME, c.SEGMENT, t.OPENED_AT
  FROM ROCKET_LAB_INTELLIGENCE.RAW.SUPPORT_TICKETS t
  JOIN ROCKET_LAB_INTELLIGENCE.RAW.CUSTOMERS c ON c.CUSTOMER_ID = t.CUSTOMER_ID;

CREATE OR REPLACE CORTEX SEARCH SERVICE RL_CUSTOMER_FEEDBACK_SEARCH
  ON VERBATIM
  ATTRIBUTES SURVEY_TYPE, NPS_CATEGORY, SEGMENT
  WAREHOUSE = ROCKET_LAB_WH
  TARGET_LAG = '1 day'
  COMMENT = 'NPS and CSAT survey comments'
AS
  SELECT s.SURVEY_ID, s.SURVEY_TYPE, s.SCORE, s.NPS_CATEGORY, s.VERBATIM,
         c.CUSTOMER_NAME, c.SEGMENT, s.RESPONSE_DATE
  FROM ROCKET_LAB_INTELLIGENCE.RAW.SURVEYS s
  JOIN ROCKET_LAB_INTELLIGENCE.RAW.CUSTOMERS c ON c.CUSTOMER_ID = s.CUSTOMER_ID;
