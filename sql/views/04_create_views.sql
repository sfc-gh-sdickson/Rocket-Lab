USE SCHEMA ANALYTICS;
USE WAREHOUSE ROCKET_LAB_WH;

-- One row per vehicle with its component condition roll-up
CREATE OR REPLACE VIEW VEHICLE_FLEET_OVERVIEW AS
SELECT
    v.VEHICLE_ID, v.VEHICLE_NAME, v.VEHICLE_TYPE, v.STATUS AS VEHICLE_STATUS,
    v.IS_REUSABLE_BOOSTER, v.REUSE_COUNT,
    DATEDIFF(DAY, v.MANUFACTURING_DATE, CURRENT_DATE()) AS AGE_DAYS,
    COUNT(c.COMPONENT_ID) AS TOTAL_COMPONENTS,
    COUNT_IF(c.STATUS = 'Operational') AS HEALTHY_COMPONENTS,
    COUNT_IF(c.STATUS = 'Degraded') AS DEGRADED_COMPONENTS,
    COUNT_IF(c.STATUS IN ('Needs Replacement','Failed')) AS CRITICAL_COMPONENTS,
    COUNT_IF(c.STATUS = 'Flown') AS FLOWN_COMPONENTS
FROM ROCKET_LAB_INTELLIGENCE.RAW.VEHICLES v
LEFT JOIN ROCKET_LAB_INTELLIGENCE.RAW.COMPONENTS c ON c.VEHICLE_ID = v.VEHICLE_ID
GROUP BY ALL;

-- Launch manifest joined to customer and site
CREATE OR REPLACE VIEW MISSION_OVERVIEW AS
SELECT
    m.MISSION_ID, m.MISSION_NUMBER, m.MISSION_NAME, m.VEHICLE_TYPE, m.MISSION_TYPE,
    m.TARGET_ORBIT, m.STATUS AS MISSION_STATUS, m.PLANNED_LAUNCH_DATE, m.ACTUAL_LAUNCH_DATE,
    m.DELAY_DAYS, m.PAYLOAD_COUNT, m.PAYLOAD_MASS_KG, m.CONTRACT_VALUE_USD,
    m.WEATHER_RISK_SCORE, m.TECHNICAL_RISK_SCORE, m.IS_FIRST_FLIGHT_CUSTOMER,
    m.RECOVERY_ATTEMPTED, m.BOOSTER_RECOVERED,
    v.VEHICLE_NAME, v.STATUS AS VEHICLE_STATUS,
    s.SITE_ID, s.SITE_NAME, s.COUNTRY AS SITE_COUNTRY,
    c.CUSTOMER_ID, c.CUSTOMER_NAME, c.CUSTOMER_TYPE, c.INDUSTRY, c.SEGMENT, c.REGION, c.SUPPORT_TIER
FROM ROCKET_LAB_INTELLIGENCE.RAW.MISSIONS m
LEFT JOIN ROCKET_LAB_INTELLIGENCE.RAW.VEHICLES v ON v.VEHICLE_ID = m.VEHICLE_ID
JOIN ROCKET_LAB_INTELLIGENCE.RAW.LAUNCH_SITES s ON s.SITE_ID = m.SITE_ID
JOIN ROCKET_LAB_INTELLIGENCE.RAW.CUSTOMERS c ON c.CUSTOMER_ID = m.CUSTOMER_ID;

-- Engine telemetry aggregated per engine per day
CREATE OR REPLACE VIEW ENGINE_TELEMETRY_DAILY AS
SELECT
    t.COMPONENT_ID, c.COMPONENT_TYPE, c.VEHICLE_ID, v.VEHICLE_NAME, v.VEHICLE_TYPE,
    t.ENGINE_MODEL, DATE_TRUNC('DAY', t.RECORDED_AT)::DATE AS TELEMETRY_DATE,
    COUNT(*) AS SAMPLE_COUNT,
    ROUND(AVG(t.CHAMBER_PRESSURE_BAR), 2) AS AVG_CHAMBER_PRESSURE_BAR,
    ROUND(MAX(t.CHAMBER_PRESSURE_BAR), 2) AS MAX_CHAMBER_PRESSURE_BAR,
    ROUND(AVG(t.THRUST_KN), 2) AS AVG_THRUST_KN,
    ROUND(AVG(t.NOZZLE_WALL_TEMP_C), 1) AS AVG_NOZZLE_TEMP_C,
    ROUND(MAX(t.NOZZLE_WALL_TEMP_C), 1) AS MAX_NOZZLE_TEMP_C,
    ROUND(AVG(t.VIBRATION_G_RMS), 2) AS AVG_VIBRATION_G,
    ROUND(MAX(t.VIBRATION_G_RMS), 2) AS MAX_VIBRATION_G,
    ROUND(AVG(t.MIXTURE_RATIO), 3) AS AVG_MIXTURE_RATIO,
    COUNT_IF(t.ERROR_CODE IS NOT NULL) AS ERROR_COUNT
FROM ROCKET_LAB_INTELLIGENCE.RAW.ENGINE_TELEMETRY t
JOIN ROCKET_LAB_INTELLIGENCE.RAW.COMPONENTS c ON c.COMPONENT_ID = t.COMPONENT_ID
JOIN ROCKET_LAB_INTELLIGENCE.RAW.VEHICLES v ON v.VEHICLE_ID = c.VEHICLE_ID
GROUP BY ALL;

-- Component health: the source for predictive maintenance and the RUL dashboard
CREATE OR REPLACE VIEW COMPONENT_HEALTH AS
SELECT
    c.COMPONENT_ID, c.COMPONENT_NAME, c.COMPONENT_TYPE, c.STATUS AS COMPONENT_STATUS,
    c.EXPECTED_LIFE_CYCLES, c.CYCLES_USED, c.INSPECTION_RUL_CYCLES,
    ROUND(100 * DIV0(c.CYCLES_USED, c.EXPECTED_LIFE_CYCLES), 1) AS LIFE_USED_PCT,
    c.LAST_INSPECTION_DATE, DATEDIFF(DAY, c.LAST_INSPECTION_DATE, CURRENT_DATE()) AS DAYS_SINCE_INSPECTION,
    v.VEHICLE_ID, v.VEHICLE_NAME, v.VEHICLE_TYPE, v.STATUS AS VEHICLE_STATUS,
    s.SUPPLIER_ID, s.SUPPLIER_NAME, s.SUPPLIER_TYPE, s.QUALITY_RATING, s.DEFECT_RATE_PPM, s.IS_SINGLE_SOURCE,
    COALESCE(tf.FAIL_COUNT, 0) AS TEST_FAIL_COUNT,
    COALESCE(tf.TEST_COUNT, 0) AS TEST_COUNT
FROM ROCKET_LAB_INTELLIGENCE.RAW.COMPONENTS c
JOIN ROCKET_LAB_INTELLIGENCE.RAW.VEHICLES v ON v.VEHICLE_ID = c.VEHICLE_ID
JOIN ROCKET_LAB_INTELLIGENCE.RAW.SUPPLIERS s ON s.SUPPLIER_ID = c.SUPPLIER_ID
LEFT JOIN (SELECT COMPONENT_ID, COUNT(*) AS TEST_COUNT, COUNT_IF(RESULT = 'Fail') AS FAIL_COUNT
           FROM ROCKET_LAB_INTELLIGENCE.RAW.TEST_RESULTS GROUP BY 1) tf ON tf.COMPONENT_ID = c.COMPONENT_ID;

-- Maintenance per vehicle and type, plus a monthly trend
CREATE OR REPLACE VIEW MAINTENANCE_ANALYSIS AS
SELECT
    m.VEHICLE_ID, v.VEHICLE_NAME, v.VEHICLE_TYPE, m.MAINTENANCE_TYPE,
    COUNT(*) AS MAINTENANCE_COUNT,
    ROUND(SUM(m.COST_USD), 2) AS TOTAL_COST_USD,
    ROUND(AVG(m.COST_USD), 2) AS AVG_COST_USD,
    ROUND(SUM(m.DURATION_HOURS), 1) AS TOTAL_HOURS,
    MIN(m.PERFORMED_AT)::DATE AS FIRST_MAINTENANCE_DATE,
    MAX(m.PERFORMED_AT)::DATE AS LAST_MAINTENANCE_DATE,
    COUNT_IF(m.PARTS_REPLACED IS NOT NULL) AS PARTS_REPLACEMENT_COUNT,
    COUNT_IF(m.OUTCOME = 'Scrapped') AS SCRAPPED_COUNT
FROM ROCKET_LAB_INTELLIGENCE.RAW.MAINTENANCE_RECORDS m
JOIN ROCKET_LAB_INTELLIGENCE.RAW.VEHICLES v ON v.VEHICLE_ID = m.VEHICLE_ID
GROUP BY ALL;

CREATE OR REPLACE VIEW MAINTENANCE_MONTHLY_TREND AS
SELECT
    DATE_TRUNC('MONTH', m.PERFORMED_AT)::DATE AS MAINTENANCE_MONTH,
    v.VEHICLE_TYPE, m.MAINTENANCE_TYPE, m.FACILITY,
    COUNT(*) AS EVENT_COUNT,
    ROUND(SUM(m.COST_USD), 2) AS TOTAL_COST_USD,
    ROUND(AVG(m.DURATION_HOURS), 1) AS AVG_HOURS
FROM ROCKET_LAB_INTELLIGENCE.RAW.MAINTENANCE_RECORDS m
JOIN ROCKET_LAB_INTELLIGENCE.RAW.VEHICLES v ON v.VEHICLE_ID = m.VEHICLE_ID
GROUP BY ALL;

-- Anomalies joined to mission and customer
CREATE OR REPLACE VIEW ANOMALY_DASHBOARD AS
SELECT
    a.ANOMALY_ID, a.ANOMALY_TYPE, a.SEVERITY, a.PHASE, a.DESCRIPTION, a.ROOT_CAUSE,
    a.REPORTED_AT, a.RESOLVED_AT, a.RESOLUTION, a.SCHEDULE_IMPACT_DAYS,
    IFF(a.RESOLVED_AT IS NULL, 'Open', 'Closed') AS ANOMALY_STATUS,
    IFF(a.RESOLVED_AT IS NULL, NULL, DATEDIFF(HOUR, a.REPORTED_AT, a.RESOLVED_AT)) AS RESOLUTION_HOURS,
    v.VEHICLE_ID, v.VEHICLE_NAME, v.VEHICLE_TYPE,
    m.MISSION_ID, m.MISSION_NAME,
    c.CUSTOMER_ID, c.CUSTOMER_NAME, c.SEGMENT
FROM ROCKET_LAB_INTELLIGENCE.RAW.ANOMALIES a
JOIN ROCKET_LAB_INTELLIGENCE.RAW.VEHICLES v ON v.VEHICLE_ID = a.VEHICLE_ID
LEFT JOIN ROCKET_LAB_INTELLIGENCE.RAW.MISSIONS m ON m.MISSION_ID = a.MISSION_ID
LEFT JOIN ROCKET_LAB_INTELLIGENCE.RAW.CUSTOMERS c ON c.CUSTOMER_ID = m.CUSTOMER_ID;

-- Supplier quality roll-up from incoming tests
CREATE OR REPLACE VIEW SUPPLIER_QUALITY AS
SELECT
    s.SUPPLIER_ID, s.SUPPLIER_NAME, s.SUPPLIER_TYPE, s.COUNTRY, s.STATUS AS SUPPLIER_STATUS,
    s.QUALITY_RATING, s.DELIVERY_RATING, s.ON_TIME_DELIVERY_PCT, s.DEFECT_RATE_PPM,
    s.RISK_SCORE, s.TOTAL_SPEND_USD, s.IS_SINGLE_SOURCE, s.IS_ITAR_REGISTERED,
    COUNT(DISTINCT c.COMPONENT_ID) AS COMPONENT_COUNT,
    COUNT(t.TEST_ID) AS TEST_COUNT,
