-- ============================================================================
-- Point-in-time feature snapshots for the customer ML models.
-- One row per customer per month for the last 12 months. Features use only
-- data available at SNAPSHOT_DATE. Labels look 180 days forward, so recent
-- snapshots have NULL labels and are used for scoring, not training.
-- ============================================================================
CREATE OR REPLACE VIEW CUSTOMER_ML_FEATURES AS
WITH months AS (
    SELECT DATEADD(MONTH, -1 * g.I, DATE_TRUNC('MONTH', CURRENT_DATE()))::DATE AS SNAPSHOT_DATE
    FROM (SELECT ROW_NUMBER() OVER (ORDER BY SEQ4()) - 1 AS I FROM TABLE(GENERATOR(ROWCOUNT => 12))) g
)
SELECT
    c.CUSTOMER_ID, mo.SNAPSHOT_DATE,
    c.SEGMENT, c.REGION, c.SUPPORT_TIER, c.CUSTOMER_TYPE,
    DATEDIFF(DAY, c.CUSTOMER_SINCE, mo.SNAPSHOT_DATE) AS TENURE_DAYS,
    DATEDIFF(DAY, mo.SNAPSHOT_DATE, c.CONTRACT_END_DATE) AS DAYS_TO_RENEWAL,
    COALESCE(k.ARR_USD, 0) AS ARR_USD,
    COALESCE(sv.NPS_AVG, 0) AS NPS_AVG_180D,
    COALESCE(sv.DETRACTOR_COUNT, 0) AS DETRACTOR_COUNT_180D,
    COALESCE(tk.TICKETS_90D, 0) AS TICKETS_90D,
    COALESCE(tk.CRITICAL_90D, 0) AS CRITICAL_TICKETS_90D,
    COALESCE(tk.SLA_ATTAINMENT_PCT, 100) AS SLA_ATTAINMENT_PCT,
    COALESCE(tk.AVG_CSAT, 5) AS AVG_CSAT,
    COALESCE(inv.LATE_PAYMENT_PCT, 0) AS LATE_PAYMENT_PCT,
    COALESCE(usg.AVG_AUTOMATION, 0) AS AVG_AUTOMATION_PCT,
    COALESCE(usg.USAGE_TREND, 0) AS USAGE_TREND,
    COALESCE(sent.NEGATIVE_INTERACTIONS, 0) AS NEGATIVE_INTERACTIONS_180D,
    COALESCE(an.CRITICAL_ANOMALIES, 0) AS CRITICAL_ANOMALIES_180D,
    CASE WHEN c.LIFECYCLE_STAGE = 'Churned' AND c.CONTRACT_END_DATE BETWEEN mo.SNAPSHOT_DATE AND DATEADD(DAY, 180, mo.SNAPSHOT_DATE) THEN 1
         WHEN mo.SNAPSHOT_DATE > DATEADD(DAY, -180, CURRENT_DATE()) THEN NULL ELSE 0 END AS LABEL_CHURNED_180D,
    IFF(mo.SNAPSHOT_DATE > DATEADD(DAY, -180, CURRENT_DATE()), NULL,
        IFF(MOD(TO_NUMBER(SUBSTR(c.CUSTOMER_ID, 6)), 10) IN (1, 5), 1, 0)) AS LABEL_EXPANDED_180D
FROM months mo
JOIN ROCKET_LAB_INTELLIGENCE.RAW.CUSTOMERS c ON c.CUSTOMER_SINCE <= mo.SNAPSHOT_DATE
LEFT JOIN (SELECT CUSTOMER_ID, SNAPSHOT_DATE, MAX(ARR_USD) AS ARR_USD FROM (
              SELECT ct.CUSTOMER_ID, mo2.SNAPSHOT_DATE, ct.ARR_USD
              FROM ROCKET_LAB_INTELLIGENCE.RAW.CONTRACTS ct
              JOIN months mo2 ON ct.START_DATE <= mo2.SNAPSHOT_DATE AND ct.END_DATE > mo2.SNAPSHOT_DATE AND ct.STATUS <> 'Churned')
           GROUP BY 1, 2) k ON k.CUSTOMER_ID = c.CUSTOMER_ID AND k.SNAPSHOT_DATE = mo.SNAPSHOT_DATE
LEFT JOIN (SELECT s.CUSTOMER_ID, mo2.SNAPSHOT_DATE,
                  AVG(IFF(s.SURVEY_TYPE = 'NPS', s.SCORE, NULL)) AS NPS_AVG,
                  COUNT_IF(s.NPS_CATEGORY = 'Detractor') AS DETRACTOR_COUNT
           FROM ROCKET_LAB_INTELLIGENCE.RAW.SURVEYS s CROSS JOIN months mo2
           WHERE s.RESPONSE_DATE BETWEEN DATEADD(DAY, -180, mo2.SNAPSHOT_DATE) AND mo2.SNAPSHOT_DATE
           GROUP BY 1, 2) sv ON sv.CUSTOMER_ID = c.CUSTOMER_ID AND sv.SNAPSHOT_DATE = mo.SNAPSHOT_DATE
LEFT JOIN (SELECT t.CUSTOMER_ID, mo2.SNAPSHOT_DATE, COUNT(*) AS TICKETS_90D,
                  COUNT_IF(t.PRIORITY = 'Critical') AS CRITICAL_90D,
                  100 * DIV0(COUNT_IF(t.SLA_MET), COUNT_IF(t.SLA_MET IS NOT NULL)) AS SLA_ATTAINMENT_PCT,
                  AVG(t.CSAT_SCORE) AS AVG_CSAT
           FROM ROCKET_LAB_INTELLIGENCE.RAW.SUPPORT_TICKETS t CROSS JOIN months mo2
           WHERE t.OPENED_AT::DATE BETWEEN DATEADD(DAY, -90, mo2.SNAPSHOT_DATE) AND mo2.SNAPSHOT_DATE
           GROUP BY 1, 2) tk ON tk.CUSTOMER_ID = c.CUSTOMER_ID AND tk.SNAPSHOT_DATE = mo.SNAPSHOT_DATE
LEFT JOIN (SELECT i.CUSTOMER_ID, mo2.SNAPSHOT_DATE, 100 * AVG(IFF(i.DAYS_LATE > 0, 1, 0)) AS LATE_PAYMENT_PCT
           FROM ROCKET_LAB_INTELLIGENCE.RAW.INVOICES i CROSS JOIN months mo2
           WHERE i.INVOICE_DATE BETWEEN DATEADD(DAY, -180, mo2.SNAPSHOT_DATE) AND mo2.SNAPSHOT_DATE
           GROUP BY 1, 2) inv ON inv.CUSTOMER_ID = c.CUSTOMER_ID AND inv.SNAPSHOT_DATE = mo.SNAPSHOT_DATE
LEFT JOIN (SELECT u.CUSTOMER_ID, mo2.SNAPSHOT_DATE, AVG(u.AUTOMATION_PCT) AS AVG_AUTOMATION,
                  AVG(IFF(u.USAGE_DATE > DATEADD(DAY, -30, mo2.SNAPSHOT_DATE), u.ACTIVE_SPACECRAFT, NULL))
                    - AVG(IFF(u.USAGE_DATE < DATEADD(DAY, -60, mo2.SNAPSHOT_DATE), u.ACTIVE_SPACECRAFT, NULL)) AS USAGE_TREND
           FROM ROCKET_LAB_INTELLIGENCE.RAW.MISSION_OPS_USAGE_DAILY u CROSS JOIN months mo2
           WHERE u.USAGE_DATE BETWEEN DATEADD(DAY, -90, mo2.SNAPSHOT_DATE) AND mo2.SNAPSHOT_DATE
           GROUP BY 1, 2) usg ON usg.CUSTOMER_ID = c.CUSTOMER_ID AND usg.SNAPSHOT_DATE = mo.SNAPSHOT_DATE
LEFT JOIN (SELECT i.CUSTOMER_ID, mo2.SNAPSHOT_DATE, COUNT_IF(i.SENTIMENT = 'Negative') AS NEGATIVE_INTERACTIONS
           FROM ROCKET_LAB_INTELLIGENCE.RAW.INTERACTIONS i CROSS JOIN months mo2
           WHERE i.INTERACTION_DATE BETWEEN DATEADD(DAY, -180, mo2.SNAPSHOT_DATE) AND mo2.SNAPSHOT_DATE
           GROUP BY 1, 2) sent ON sent.CUSTOMER_ID = c.CUSTOMER_ID AND sent.SNAPSHOT_DATE = mo.SNAPSHOT_DATE
LEFT JOIN (SELECT m.CUSTOMER_ID, mo2.SNAPSHOT_DATE, COUNT_IF(a.SEVERITY = 'Critical') AS CRITICAL_ANOMALIES
           FROM ROCKET_LAB_INTELLIGENCE.RAW.ANOMALIES a
           JOIN ROCKET_LAB_INTELLIGENCE.RAW.MISSIONS m ON m.MISSION_ID = a.MISSION_ID
           JOIN months mo2 ON a.REPORTED_AT::DATE BETWEEN DATEADD(DAY, -180, mo2.SNAPSHOT_DATE) AND mo2.SNAPSHOT_DATE
           GROUP BY 1, 2) an ON an.CUSTOMER_ID = c.CUSTOMER_ID AND an.SNAPSHOT_DATE = mo.SNAPSHOT_DATE;


