LEFT JOIN ROCKET_LAB_INTELLIGENCE.RAW.COMPONENTS c ON c.SUPPLIER_ID = s.SUPPLIER_ID
LEFT JOIN ROCKET_LAB_INTELLIGENCE.RAW.TEST_RESULTS t ON t.COMPONENT_ID = c.COMPONENT_ID
GROUP BY ALL;

-- ============================================================================
-- CUSTOMER 360
-- ============================================================================
CREATE OR REPLACE VIEW CUSTOMER_360 AS
SELECT
    c.CUSTOMER_ID, c.CUSTOMER_NAME, c.CUSTOMER_TYPE, c.INDUSTRY, c.SEGMENT, c.REGION,
    c.COUNTRY, c.ACCOUNT_MANAGER, c.CSM_NAME, c.SUPPORT_TIER, c.LIFECYCLE_STAGE,
    c.CUSTOMER_SINCE, c.CONTRACT_END_DATE,
    DATEDIFF(DAY, CURRENT_DATE(), c.CONTRACT_END_DATE) AS DAYS_TO_RENEWAL,
    ROUND(k.ACTIVE_ARR, 2) AS ACTIVE_ARR_USD,
    k.ACTIVE_CONTRACTS,
    COALESCE(m.MISSION_COUNT, 0) AS MISSION_COUNT,
    COALESCE(m.SUCCESS_COUNT, 0) AS SUCCESSFUL_MISSIONS,
    COALESCE(m.FAILURE_COUNT, 0) AS FAILED_MISSIONS,
    ROUND(m.BACKLOG_USD, 2) AS LAUNCH_BACKLOG_USD,
    COALESCE(sc.SPACECRAFT_COUNT, 0) AS SPACECRAFT_COUNT,
    COALESCE(sc.NOMINAL_COUNT, 0) AS NOMINAL_SPACECRAFT,
    ROUND(nps.NPS_SCORE, 1) AS LATEST_NPS,
    nps.NPS_CATEGORY AS LATEST_NPS_CATEGORY,
    COALESCE(tk.OPEN_TICKETS, 0) AS OPEN_TICKETS,
    COALESCE(tk.CRITICAL_OPEN, 0) AS CRITICAL_OPEN_TICKETS,
    ROUND(tk.SLA_ATTAINMENT_PCT, 1) AS SLA_ATTAINMENT_PCT,
    ROUND(inv.LATE_PAYMENT_PCT, 1) AS LATE_PAYMENT_PCT,
    ROUND(inv.OVERDUE_USD, 2) AS OVERDUE_USD,
    COALESCE(an.CRITICAL_ANOMALIES, 0) AS CRITICAL_ANOMALIES,
    ROUND(usg.AVG_ACTIVE_SPACECRAFT_90D, 2) AS AVG_ACTIVE_SPACECRAFT_90D,
    ROUND(usg.AVG_AUTOMATION_PCT_90D, 1) AS AVG_AUTOMATION_PCT_90D,
    ROUND(usg.AVG_COMMAND_SUCCESS_90D, 1) AS AVG_COMMAND_SUCCESS_90D
FROM ROCKET_LAB_INTELLIGENCE.RAW.CUSTOMERS c
LEFT JOIN (SELECT CUSTOMER_ID, SUM(IFF(STATUS = 'Active', ARR_USD, 0)) AS ACTIVE_ARR, COUNT_IF(STATUS = 'Active') AS ACTIVE_CONTRACTS
           FROM ROCKET_LAB_INTELLIGENCE.RAW.CONTRACTS GROUP BY 1) k ON k.CUSTOMER_ID = c.CUSTOMER_ID
LEFT JOIN (SELECT CUSTOMER_ID, COUNT(*) AS MISSION_COUNT,
                  COUNT_IF(STATUS = 'Success') AS SUCCESS_COUNT, COUNT_IF(STATUS = 'Failure') AS FAILURE_COUNT,
                  SUM(IFF(ACTUAL_LAUNCH_DATE IS NULL, CONTRACT_VALUE_USD, 0)) AS BACKLOG_USD
           FROM ROCKET_LAB_INTELLIGENCE.RAW.MISSIONS GROUP BY 1) m ON m.CUSTOMER_ID = c.CUSTOMER_ID
LEFT JOIN (SELECT CUSTOMER_ID, COUNT(*) AS SPACECRAFT_COUNT, COUNT_IF(STATUS = 'On Orbit - Nominal') AS NOMINAL_COUNT
           FROM ROCKET_LAB_INTELLIGENCE.RAW.CUSTOMER_SPACECRAFT GROUP BY 1) sc ON sc.CUSTOMER_ID = c.CUSTOMER_ID
LEFT JOIN (SELECT CUSTOMER_ID, SCORE AS NPS_SCORE, NPS_CATEGORY
           FROM ROCKET_LAB_INTELLIGENCE.RAW.SURVEYS WHERE SURVEY_TYPE = 'NPS'
           QUALIFY ROW_NUMBER() OVER (PARTITION BY CUSTOMER_ID ORDER BY RESPONSE_DATE DESC) = 1) nps ON nps.CUSTOMER_ID = c.CUSTOMER_ID
LEFT JOIN (SELECT CUSTOMER_ID, COUNT_IF(STATUS = 'Open') AS OPEN_TICKETS,
                  COUNT_IF(STATUS = 'Open' AND PRIORITY = 'Critical') AS CRITICAL_OPEN,
                  100 * DIV0(COUNT_IF(SLA_MET), COUNT_IF(SLA_MET IS NOT NULL)) AS SLA_ATTAINMENT_PCT
           FROM ROCKET_LAB_INTELLIGENCE.RAW.SUPPORT_TICKETS GROUP BY 1) tk ON tk.CUSTOMER_ID = c.CUSTOMER_ID
LEFT JOIN (SELECT CUSTOMER_ID, 100 * AVG(IFF(DAYS_LATE > 0, 1, 0)) AS LATE_PAYMENT_PCT,
                  SUM(IFF(PAYMENT_STATUS = 'Overdue', AMOUNT_USD, 0)) AS OVERDUE_USD
           FROM ROCKET_LAB_INTELLIGENCE.RAW.INVOICES GROUP BY 1) inv ON inv.CUSTOMER_ID = c.CUSTOMER_ID
LEFT JOIN (SELECT m.CUSTOMER_ID, COUNT_IF(a.SEVERITY = 'Critical') AS CRITICAL_ANOMALIES
           FROM ROCKET_LAB_INTELLIGENCE.RAW.ANOMALIES a JOIN ROCKET_LAB_INTELLIGENCE.RAW.MISSIONS m ON m.MISSION_ID = a.MISSION_ID
           GROUP BY 1) an ON an.CUSTOMER_ID = c.CUSTOMER_ID
LEFT JOIN (SELECT CUSTOMER_ID, AVG(ACTIVE_SPACECRAFT) AS AVG_ACTIVE_SPACECRAFT_90D,
                  AVG(AUTOMATION_PCT) AS AVG_AUTOMATION_PCT_90D, AVG(COMMAND_SUCCESS_PCT) AS AVG_COMMAND_SUCCESS_90D
           FROM ROCKET_LAB_INTELLIGENCE.RAW.MISSION_OPS_USAGE_DAILY
           WHERE USAGE_DATE >= DATEADD(DAY, -90, CURRENT_DATE()) GROUP BY 1) usg ON usg.CUSTOMER_ID = c.CUSTOMER_ID;

CREATE OR REPLACE VIEW CUSTOMER_REVENUE_MONTHLY AS
